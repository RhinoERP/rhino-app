CREATE OR REPLACE FUNCTION public.prepare_whatsapp_outbox(p_job_id uuid,p_lease_token uuid,p_text text,p_order_prompt boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE j agent_jobs%ROWTYPE; x whatsapp_outbox%ROWTYPE;
BEGIN
  SELECT * INTO j FROM agent_jobs WHERE id=p_job_id AND lease_token=p_lease_token AND status='PROCESSING' AND lease_expires_at>now() AND job_type='PROCESS_CONVERSATION' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'El trabajo perdió su exclusión'; END IF;
  INSERT INTO whatsapp_outbox(source_message_id,organization_id,conversation_id,text,order_prompt)
  VALUES(j.source_message_id,j.organization_id,j.conversation_id,p_text,p_order_prompt) ON CONFLICT DO NOTHING;
  SELECT * INTO x FROM whatsapp_outbox WHERE source_message_id=j.source_message_id FOR UPDATE;
  IF x.status='SENDING' THEN
    UPDATE whatsapp_outbox SET status='UNKNOWN',updated_at=now() WHERE source_message_id=j.source_message_id RETURNING * INTO x;
  ELSIF x.status='PENDING' THEN
    IF j.source_message_id <> (SELECT m.id FROM whatsapp_messages m WHERE m.conversation_id=j.conversation_id AND m.direction='INBOUND' ORDER BY m.sequence_no DESC LIMIT 1) THEN
      UPDATE whatsapp_outbox SET status='CANCELLED',updated_at=now() WHERE source_message_id=j.source_message_id RETURNING * INTO x;
    ELSE
      UPDATE whatsapp_outbox SET status='SENDING',lease_token=p_lease_token,updated_at=now() WHERE source_message_id=j.source_message_id RETURNING * INTO x;
    END IF;
  END IF;
  RETURN to_jsonb(x);
END $$;

CREATE OR REPLACE FUNCTION public.complete_whatsapp_outbox(p_source_message_id uuid,p_lease_token uuid,p_status text,p_external_message_id text DEFAULT null)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE x whatsapp_outbox%ROWTYPE; m whatsapp_messages%ROWTYPE;
BEGIN
  IF p_status NOT IN ('PENDING','SENT','UNKNOWN','CANCELLED') THEN RAISE EXCEPTION 'Estado inválido'; END IF;
  SELECT * INTO x FROM whatsapp_outbox WHERE source_message_id=p_source_message_id AND lease_token=p_lease_token AND status IN ('SENDING','UNKNOWN') FOR UPDATE;
  IF NOT FOUND THEN RETURN false; END IF;
  IF p_status='SENT' THEN
    IF coalesce(p_external_message_id,'')='' THEN RAISE EXCEPTION 'Falta el identificador externo'; END IF;
    SELECT * INTO m FROM whatsapp_messages WHERE id=p_source_message_id AND organization_id=x.organization_id AND conversation_id=x.conversation_id;
    INSERT INTO whatsapp_messages(organization_id,integration_id,conversation_id,external_message_id,direction,message_type,content,payload,delivery_status,sent_at)
    VALUES(m.organization_id,m.integration_id,m.conversation_id,p_external_message_id,'OUTBOUND','TEXT',x.text,jsonb_build_object('provider','META_CLOUD','sourceMessageId',m.id,'orderPrompt',x.order_prompt),'SENT',now()) ON CONFLICT(external_message_id) DO NOTHING;
    UPDATE whatsapp_conversations SET last_message_at=now() WHERE id=m.conversation_id;
  END IF;
  UPDATE whatsapp_outbox SET status=p_status,external_message_id=coalesce(p_external_message_id,external_message_id),updated_at=now() WHERE source_message_id=p_source_message_id;
  RETURN true;
END $$;
