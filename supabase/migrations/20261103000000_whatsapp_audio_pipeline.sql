CREATE OR REPLACE FUNCTION public.enqueue_whatsapp_audio() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_sim boolean; v_enabled boolean;
BEGIN
  IF NEW.direction <> 'INBOUND' OR NEW.message_type <> 'AUDIO' THEN RETURN NEW; END IF;
  SELECT wi.phone_number_id LIKE 'rhinos-local-simulator:%',
    o.is_active AND CASE WHEN wi.phone_number_id LIKE 'rhinos-local-simulator:%'
      THEN o.whatsapp_sandbox_enabled AND o.whatsapp_sandbox_audio_enabled
      ELSE o.whatsapp_enabled AND o.whatsapp_audio_enabled AND wi.status='ACTIVE' END
  INTO v_sim,v_enabled FROM whatsapp_integrations wi JOIN organizations o ON o.id=wi.organization_id
  WHERE wi.id=NEW.integration_id AND wi.organization_id=NEW.organization_id;
  IF NOT coalesce(v_enabled,false) THEN RETURN NEW; END IF;
  INSERT INTO whatsapp_audio_assets(message_id,organization_id,integration_id,conversation_id,media_id,storage_path,stored)
  VALUES(NEW.id,NEW.organization_id,NEW.integration_id,NEW.conversation_id,NEW.payload->'audio'->>'id',
    coalesce(NEW.payload->>'audio_storage_path',NEW.organization_id::text||'/'||NEW.conversation_id::text||'/'||NEW.id::text||'/audio'),v_sim)
  ON CONFLICT DO NOTHING;
  INSERT INTO agent_jobs(organization_id,integration_id,conversation_id,source_message_id,job_type,execution_mode,status)
  VALUES(NEW.organization_id,NEW.integration_id,NEW.conversation_id,NEW.id,'TRANSCRIBE_AUDIO',CASE WHEN v_sim THEN 'INLINE' ELSE 'DAEMON' END,'PENDING'),
        (NEW.organization_id,NEW.integration_id,NEW.conversation_id,NEW.id,'PROCESS_CONVERSATION',CASE WHEN v_sim THEN 'INLINE' ELSE 'DAEMON' END,'WAITING')
  ON CONFLICT(source_message_id,job_type) DO NOTHING;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS enqueue_whatsapp_audio ON public.whatsapp_messages;
CREATE TRIGGER enqueue_whatsapp_audio AFTER INSERT ON public.whatsapp_messages FOR EACH ROW EXECUTE FUNCTION public.enqueue_whatsapp_audio();

CREATE OR REPLACE FUNCTION public.complete_whatsapp_audio_upload(p_upload_id uuid,p_actor_id uuid) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE u whatsapp_audio_uploads%ROWTYPE; c whatsapp_conversations%ROWTYPE;
BEGIN
  SELECT * INTO u FROM whatsapp_audio_uploads WHERE id=p_upload_id AND actor_id=p_actor_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Carga de audio no encontrada'; END IF;
  SELECT * INTO c FROM whatsapp_conversations WHERE id=u.conversation_id AND organization_id=u.organization_id AND integration_id=u.integration_id AND assigned_user_id=p_actor_id FOR UPDATE;
  IF NOT FOUND OR c.status <> 'ACTIVE' OR NOT public.is_whatsapp_mode_enabled(u.organization_id,'rhinos-local-simulator:') THEN RAISE EXCEPTION 'La sesión no está disponible'; END IF;
  IF NOT EXISTS(SELECT 1 FROM organizations WHERE id=u.organization_id AND whatsapp_sandbox_audio_enabled) THEN RAISE EXCEPTION 'Los audios no están habilitados'; END IF;
  IF u.message_id IS NOT NULL THEN RETURN u.message_id; END IF;
  IF u.expires_at <= now() THEN RAISE EXCEPTION 'La carga de audio venció'; END IF;
  IF NOT EXISTS(SELECT 1 FROM storage.objects WHERE bucket_id='whatsapp-audio' AND name=u.storage_path) THEN RAISE EXCEPTION 'Todavía no se recibió el archivo'; END IF;
  INSERT INTO whatsapp_messages(id,organization_id,integration_id,conversation_id,external_message_id,direction,message_type,content,payload,delivery_status)
  VALUES(u.id,u.organization_id,u.integration_id,u.conversation_id,'local-simulator-audio:'||u.id,'INBOUND','AUDIO',null,
    jsonb_build_object('source','LOCAL_SIMULATOR','sentToWhatsApp',false,'audio_storage_path',u.storage_path),'RECEIVED');
  UPDATE whatsapp_audio_uploads SET message_id=u.id WHERE id=u.id;
  UPDATE whatsapp_conversations SET last_message_at=now() WHERE id=c.id;
  RETURN u.id;
END $$;

CREATE OR REPLACE FUNCTION public.claim_whatsapp_job_v2(p_worker_id text,p_job_type text,p_execution_mode text DEFAULT 'DAEMON',p_job_id uuid DEFAULT null,p_capacity integer DEFAULT 8)
RETURNS SETOF public.agent_jobs LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE j agent_jobs%ROWTYPE; v_sim boolean;
BEGIN
  IF coalesce(btrim(p_worker_id),'')='' OR p_job_type NOT IN ('TRANSCRIBE_AUDIO','PROCESS_CONVERSATION') OR p_execution_mode NOT IN ('INLINE','DAEMON') THEN RAISE EXCEPTION 'Configuración de worker inválida'; END IF;
  -- Serialize admission briefly; no database transaction spans a provider request.
  PERFORM pg_advisory_xact_lock(hashtextextended('whatsapp-claim-'||p_job_type,0));
  IF (SELECT count(*) FROM agent_jobs WHERE job_type=p_job_type AND status='PROCESSING' AND lease_expires_at>now()) >= greatest(1,least(p_capacity,32)) THEN RETURN; END IF;
  FOR j IN SELECT q.* FROM agent_jobs q
    JOIN whatsapp_integrations wi ON wi.id=q.integration_id AND wi.organization_id=q.organization_id
    JOIN whatsapp_conversations c ON c.id=q.conversation_id AND c.organization_id=q.organization_id
    JOIN organizations o ON o.id=q.organization_id
    WHERE q.job_type=p_job_type AND q.execution_mode=p_execution_mode AND (p_job_id IS NULL OR q.id=p_job_id)
      AND ((q.status IN ('PENDING','RETRY') AND q.available_at<=now()) OR (q.status='PROCESSING' AND q.lease_expires_at<=now()))
      AND o.is_active AND c.status='ACTIVE'
      AND public.is_whatsapp_mode_enabled(o.id,wi.phone_number_id)
      AND ((wi.phone_number_id LIKE 'rhinos-local-simulator:%' AND wi.status='DRAFT') OR wi.status='ACTIVE')
      AND (p_job_type<>'TRANSCRIBE_AUDIO' OR CASE WHEN wi.phone_number_id LIKE 'rhinos-local-simulator:%' THEN o.whatsapp_sandbox_audio_enabled ELSE o.whatsapp_audio_enabled END)
      AND NOT EXISTS(SELECT 1 FROM whatsapp_outbox x WHERE x.conversation_id=q.conversation_id AND x.status='UNKNOWN')
      AND NOT EXISTS(SELECT 1 FROM agent_jobs active WHERE active.organization_id=q.organization_id AND active.job_type=p_job_type AND active.status='PROCESSING' AND active.lease_expires_at>now() AND active.id<>q.id GROUP BY active.organization_id HAVING count(*)>=2)
    ORDER BY q.available_at,q.created_at FOR UPDATE OF q SKIP LOCKED LIMIT 50
  LOOP
    IF p_job_type='PROCESS_CONVERSATION' THEN
      IF NOT pg_try_advisory_xact_lock(hashtextextended(j.conversation_id::text,0)) THEN CONTINUE; END IF;
      IF EXISTS(SELECT 1 FROM agent_jobs active WHERE active.conversation_id=j.conversation_id AND active.job_type='PROCESS_CONVERSATION' AND active.status='PROCESSING' AND active.lease_expires_at>now() AND active.id<>j.id) THEN CONTINUE; END IF;
      IF EXISTS(SELECT 1 FROM whatsapp_audio_assets a JOIN whatsapp_messages m ON m.id=a.message_id JOIN whatsapp_messages src ON src.id=j.source_message_id
        WHERE a.conversation_id=j.conversation_id AND m.sequence_no<=src.sequence_no AND a.status IN ('PENDING','PROCESSING')) THEN CONTINUE; END IF;
    END IF;
    UPDATE agent_jobs SET status='PROCESSING',attempts=attempts+1,locked_at=now(),locked_by=p_worker_id,lease_token=gen_random_uuid(),lease_expires_at=now()+interval '180 seconds',last_error=null WHERE id=j.id RETURNING * INTO j;
    RETURN NEXT j; RETURN;
  END LOOP;
END $$;

